 async function onlineLookup(local,fetcher){const doi=doiFromText(local.doi)||'',title=clean(local.title);const candidates=[];
  // A verified DOI is a hard identifier. Never silently borrow journal/author
  // metadata from a different DOI just because its title looks similar.
  const compatible=meta=>!doi||!!meta.doi&&meta.doi.toLowerCase()===doi.toLowerCase();
  if(doi){try{const r=await request('https://api.crossref.org/works/'+encodeURIComponent(doi),fetcher);if(r.message&&doiFromText(r.message.DOI).toLowerCase()===doi.toLowerCase())candidates.push({meta:mapCrossref(r.message),score:1,verifiedDOI:true})}catch{}}
  if(!candidates.length&&title.length>=14){try{const q=new URLSearchParams({'query.bibliographic':title,'rows':'5','select':'title,container-title,published,issued,DOI,author,type'});const r=await request('https://api.crossref.org/works?'+q,fetcher);for(const item of r.message?.items||[]){const meta=mapCrossref(item);if(compatible(meta))candidates.push({meta,score:similarity(title,meta.title)})}}catch{}}
  if(!candidates.some(x=>x.score>=.90&&x.meta.journal)){
   try{let url;if(doi)url='https://api.openalex.org/works/https://doi.org/'+encodeURIComponent(doi);else url='https://api.openalex.org/works?'+new URLSearchParams({'search.title':title,per_page:'5'});
    const r=await request(url,fetcher);for(const item of r.results||[r]){if(!item?.id)continue;const meta=mapOpenAlex(item);if(compatible(meta))candidates.push({meta,score:doi&&meta.doi.toLowerCase()===doi.toLowerCase()?1:similarity(title,meta.title),verifiedDOI:!!doi&&meta.doi.toLowerCase()===doi.toLowerCase()})}
   }catch{}
  }
  candidates.sort((a,b)=>b.score-a.score);const best=candidates.find(x=>(x.verifiedDOI||x.score>=.94)&&(x.meta.journal||x.meta.year));return best?{...best.meta,score:best.score,verifiedDOI:!!best.verifiedDOI}:null;
 }
