 function similarity(a,b){
 const normalized=v=>titleNorm(v).replace(/([\u3400-\u9fff])\s+(?=[\u3400-\u9fff])/g,'$1');
 const x=normalized(a),y=normalized(b);if(!x||!y)return 0;if(x===y)return 1;
 // Long Chinese titles have no word separators. Compare character bigrams to
 // avoid treating an entire line as one token and accepting unrelated papers.
 const tokens=s=>s.split(' ').filter(Boolean).flatMap(word=>{
  if(/[\u3400-\u9fff]/.test(word)&&word.length>=3)return Array.from({length:word.length-1},(_,i)=>word.slice(i,i+2));
  return [word];
 });
 const A=new Set(tokens(x)),B=new Set(tokens(y));
 const common=[...A].filter(v=>B.has(v)).length;
 // F1-like Dice similarity punishes partial matches without assuming word boundaries.
 return .90*(2*common/Math.max(1,A.size+B.size))+.10*Math.min(x.length,y.length)/Math.max(x.length,y.length);
}
